from typing import List, Tuple

def get_category(key: str) -> dict:
    """Get a first aid category by key."""
    return FIRST_AID_CATEGORIES.get(key, {})


def list_categories() -> List[Tuple[str, str, str]]:
    """List all first aid categories."""
    return [
        (data["icon"], data["name"], data["name_en"])
        for key, data in FIRST_AID_CATEGORIES.items()
    ]


def get_all_keys() -> List[str]:
    """Get all category keys."""
    return list(FIRST_AID_CATEGORIES.keys())
